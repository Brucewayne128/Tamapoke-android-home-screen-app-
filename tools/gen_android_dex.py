#!/usr/bin/env python3
"""Generates the Pokedex table for the Android launcher (android/) from dex_data.py.

  python3 tools/gen_android_dex.py

Same rarity rules as gen_dex.py, so the launcher and the firmware agree on
names, evolution levels and which species come out of eggs.
"""
import os
import sys

sys.path.insert(0, os.path.dirname(__file__))
from dex_data import DEX, TYPE_ACCENTS, RARE, LEGENDARY

OUT = os.path.join(os.path.dirname(__file__), '..', 'android', 'app', 'src', 'main',
                   'java', 'com', 'tamapoke', 'launcher', 'Dex.kt')


def main():
    evolved = {d[4] for d in DEX if d[4]} | {135, 136}
    out = [
        "// GENERATED by tools/gen_android_dex.py from tools/dex_data.py - do not edit\n",
        "package com.tamapoke.launcher\n\n",
        "/** rarity: 0 = only by evolution, 1 = common, 2 = rare, 3 = legendary */\n",
        "data class DexEntry(\n",
        "    val name: String,\n",
        "    val evolvesTo: Int,\n",
        "    val evolveLevel: Int,\n",
        "    val rarity: Int,\n",
        "    val accent: Long,\n",
        ")\n\n",
        "object Dex {\n",
        "    const val COUNT = 151\n",
        "    const val EEVEE = 133\n",
        "    val STARTERS = intArrayOf(1, 4, 7)\n\n",
        "    private val table = arrayOf(\n",
        '        DexEntry("?", 0, 0, 0, 0xFF2A2A2A),\n',
    ]
    for num, _slug, display, typ, evo, lvl in DEX:
        if num in evolved:
            rar = 0
        elif num in LEGENDARY:
            rar = 3
        elif num in RARE:
            rar = 2
        else:
            rar = 1
        acc = TYPE_ACCENTS[typ][1:].upper()
        out.append(f'        DexEntry("{display}", {evo}, {lvl}, {rar}, 0xFF{acc}),  // {num} {typ}\n')
    out += [
        "    )\n\n",
        "    operator fun get(dex: Int): DexEntry = table[if (dex in 1..COUNT) dex else 0]\n",
        "}\n",
    ]
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(''.join(out))
    print('wrote', os.path.relpath(OUT))


if __name__ == '__main__':
    main()
